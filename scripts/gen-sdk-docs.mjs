// Dev tool: dump the exported surface of every SDK domain module into
// docs/sdk-surface.md, so page authors (human or agent) can see the exact call
// signatures without opening thirteen files.
//
//   node scripts/gen-sdk-docs.mjs
import { readFileSync, readdirSync, writeFileSync, mkdirSync } from 'node:fs'
import { join, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const domainsDir = join(root, 'lib', 'api', 'domains')
const typesDir = join(root, 'lib', 'api', 'types')

const out = ['# SDK surface', '', 'Auto-generated by `node scripts/gen-sdk-docs.mjs`. Do not edit by hand.', '']

function signatures(file) {
  const src = readFileSync(file, 'utf8')
  const found = []
  const fnRe = /^export (?:async )?function (\w+)\s*\(([\s\S]*?)\)\s*(?::\s*([^{;\n]+?))?\s*\{/gm
  for (const m of src.matchAll(fnRe)) {
    const args = m[2].replace(/\s+/g, ' ').trim()
    const ret = (m[3] ?? 'void').replace(/\s+/g, ' ').trim()
    found.push({ name: m[1], args, ret })
  }
  const ifaceRe = /^export (?:interface|type) (\w+)/gm
  const types = [...src.matchAll(ifaceRe)].map((m) => m[1])
  return { functions: found, types }
}

out.push('## Domain modules (`lib/api/domains`)', '')
for (const file of readdirSync(domainsDir).filter((f) => f.endsWith('.ts')).sort()) {
  const { functions } = signatures(join(domainsDir, file))
  const mod = file.replace(/\.ts$/, '')
  out.push(`### ${mod}`, '')
  out.push('```ts')
  for (const fn of functions) out.push(`${fn.name}(${fn.args}): ${fn.ret}`)
  out.push('```', '')
}

out.push('## Parameter / result types (`lib/api/types`)', '')
for (const file of readdirSync(typesDir).filter((f) => f.endsWith('.ts')).sort()) {
  const src = readFileSync(join(typesDir, file), 'utf8')
  const names = [...src.matchAll(/^export (?:interface|type|const) (\w+)/gm)].map((m) => m[1])
  if (!names.length) continue
  out.push(`### ${file.replace(/\.ts$/, '')}`, '')
  out.push(names.map((n) => `\`${n}\``).join(' · '), '')
}

out.push('## Calling convention', '')
out.push(
  [
    '- Import from `@/lib/api/domains/<module>`; never call `apiRequest` or `fetch` directly.',
    '- Wrap reads in `useQuery` with a key from `@/lib/api/query-keys` (`queryKeys.*`), always seeded with the active target from `useTargetKey()`.',
    '- Wrap writes in `useMutation`; on success `toast.success(...)` and `queryClient.invalidateQueries({ queryKey })`.',
    '- Downloads use `apiDownload(endpoint, params)` from `@/lib/api/client` (or a domain wrapper such as `zones.exportZone`).',
    '- Errors are `DnsApiError`; use `describeError()` for display and `isAuthError()` to trigger re-auth.',
    '- Gate mutation controls on `useSession().canModify(section)` / `canDelete(section)`.',
  ].join('\n'),
  '',
)

mkdirSync(join(root, 'docs'), { recursive: true })
writeFileSync(join(root, 'docs', 'sdk-surface.md'), out.join('\n') + '\n')
console.log(`docs/sdk-surface.md written`)
