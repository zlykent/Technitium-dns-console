// Dev tool: generate lib/api/registry.ts (and docs/api-endpoints.md) straight
// from the endpoint paths + call-site params harvested from the official
// console JS, so no endpoint can be missed or misspelled by hand.
//
//   node scripts/probe/gen-registry.mjs <consoleJsDir>
import { readFileSync, readdirSync, writeFileSync, mkdirSync } from 'node:fs'
import { join, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const consoleDir = process.argv[2]
if (!consoleDir) {
  console.error('usage: gen-registry.mjs <consoleJsDir>')
  process.exit(1)
}
const repoRoot = join(dirname(fileURLToPath(import.meta.url)), '..', '..')

// ------------------------------------------------------------- harvesting
const jsFiles = readdirSync(consoleDir).filter((f) => f.endsWith('.js'))
const paths = new Set()
for (const f of jsFiles) {
  const src = readFileSync(join(consoleDir, f), 'utf8')
  for (const m of src.matchAll(/(?<![\w/.])api\/([A-Za-z0-9_/]+)/g)) {
    const id = m[1].replace(/\/+$/, '')
    if (id && id.includes('/')) paths.add(id)
    else if (id === 'status') paths.add(id)
  }
}

// call-site params captured earlier by extract-params.mjs
let paramsByEndpoint = new Map()
try {
  const raw = JSON.parse(readFileSync(join(consoleDir, 'endpoints-params.json'), 'utf8'))
  for (const e of raw) paramsByEndpoint.set(e.endpoint, e)
} catch {
  console.warn('endpoints-params.json not found — methods default to GET')
}

// ------------------------------------------------------------- policy tables
/** Endpoints reachable without a session token. */
const NO_AUTH = new Set(['status', 'user/login'])

/** Technitium is inconsistent: these three return fields at the top level. */
const FLAT = new Set(['status', 'user/login', 'user/session/get'])

/** Binary/text downloads — streamed through the proxy, never JSON-parsed. */
const FILE_KIND = new Set([
  'zones/export',
  'allowed/export',
  'blocked/export',
  'logs/export',
  'logs/download',
  'settings/backup',
])

/** multipart/form-data uploads (zone files, block lists, config restore). */
const UPLOAD_KIND = new Set(['zones/import', 'zones/create', 'allowed/import', 'blocked/import', 'settings/restore', 'apps/install', 'apps/update'])

const DOMAIN_ORDER = [
  'system', 'user', 'admin', 'dashboard', 'zones', 'records', 'dnssec',
  'cache', 'allowed', 'blocked', 'apps', 'dhcp', 'logs', 'settings', 'dnsClient',
]

function domainOf(id) {
  if (id === 'status') return 'system'
  if (id.startsWith('user/')) return 'user'
  if (id.startsWith('admin/')) return 'admin'
  if (id.startsWith('dashboard/')) return 'dashboard'
  if (id.startsWith('zones/dnssec/')) return 'dnssec'
  if (id.startsWith('zones/records/')) return 'records'
  if (id.startsWith('zones/')) return 'zones'
  if (id.startsWith('cache/')) return 'cache'
  if (id.startsWith('allowed/')) return 'allowed'
  if (id.startsWith('blocked/')) return 'blocked'
  if (id.startsWith('apps/')) return 'apps'
  if (id.startsWith('dhcp/')) return 'dhcp'
  if (id.startsWith('logs/')) return 'logs'
  if (id.startsWith('settings/')) return 'settings'
  if (id.startsWith('dnsClient/')) return 'dnsClient'
  throw new Error(`cannot infer domain for ${id}`)
}

const ids = [...paths].sort((a, b) => DOMAIN_ORDER.indexOf(domainOf(a)) - DOMAIN_ORDER.indexOf(domainOf(b)) || a.localeCompare(b))

// ------------------------------------------------------------- emit registry
const lines = []
lines.push(`// AUTO-GENERATED by scripts/probe/gen-registry.mjs — do not edit by hand.
// Regenerate with:  node scripts/probe/gen-registry.mjs .probe/console-js
//
// Source of truth harvested from the Technitium DNS Server v15.4 web console.
// Every entry doubles as (1) the proxy path allowlist, (2) the HTTP method
// table, (3) the auth/envelope/response-kind policy, and (4) the SDK's
// EndpointId literal union.
//
// Endpoint count: ${ids.length}

export const API_DOMAINS = [
${DOMAIN_ORDER.map((d) => `  '${d}',`).join('\n')}
] as const

export type ApiDomain = (typeof API_DOMAINS)[number]

export type ApiMethod = 'GET' | 'POST'

/** How Technitium wraps a successful payload for this endpoint. */
export type ApiEnvelope = 'wrapped' | 'flat'

/** What the proxy does with the upstream body. */
export type ApiKind = 'json' | 'file' | 'upload'

export interface EndpointDef {
  /** HTTP verbs the upstream endpoint accepts; the proxy rejects anything else. */
  readonly methods: readonly ApiMethod[]
  readonly auth: 'none' | 'token'
  readonly envelope: ApiEnvelope
  readonly kind: ApiKind
  readonly domain: ApiDomain
}

export const ENDPOINTS = {`)

let lastDomain = ''
for (const id of ids) {
  const dom = domainOf(id)
  if (dom !== lastDomain) {
    lines.push(`  // ---- ${dom} ----`)
    lastDomain = dom
  }
  const meta = paramsByEndpoint.get(id)
  const observed = meta?.methods?.length ? meta.methods : ['GET']
  const methods = [...new Set(observed.map((m) => (m === 'POST' ? 'POST' : 'GET')))]
  const auth = NO_AUTH.has(id) ? 'none' : 'token'
  const envelope = FLAT.has(id) ? 'flat' : 'wrapped'
  const kind = FILE_KIND.has(id) ? 'file' : UPLOAD_KIND.has(id) ? 'upload' : 'json'
  lines.push(
    `  '${id}': { methods: [${methods.map((m) => `'${m}'`).join(', ')}], auth: '${auth}', envelope: '${envelope}', kind: '${kind}', domain: '${dom}' },`,
  )
}

lines.push(`} as const satisfies Record<string, EndpointDef>

export type EndpointId = keyof typeof ENDPOINTS

/** Narrow an endpoint id to a single domain — used to type the SDK modules. */
export type EndpointIdOf<D extends ApiDomain> = {
  [K in EndpointId]: (typeof ENDPOINTS)[K]['domain'] extends D ? K : never
}[EndpointId]

export const ENDPOINT_COUNT = ${ids.length} as const

/** Runtime guard used by the proxy to reject anything outside the allowlist. */
export function isKnownEndpoint(path: string): path is EndpointId {
  return Object.hasOwn(ENDPOINTS, path)
}

export function getEndpoint(path: string): EndpointDef | undefined {
  return isKnownEndpoint(path) ? ENDPOINTS[path] : undefined
}`)

mkdirSync(join(repoRoot, 'lib', 'api'), { recursive: true })
writeFileSync(join(repoRoot, 'lib', 'api', 'registry.ts'), lines.join('\n') + '\n')

// ------------------------------------------------------------- emit docs
const doc = []
doc.push(`# Technitium DNS Server API surface (v15.4)

Auto-generated by \`scripts/probe/gen-registry.mjs\` from the running server's own
web console bundle. **${ids.length} endpoints.**

Legend — *auth*: \`none\` = reachable without a session token. *envelope*: \`flat\` =
payload fields sit at the top level, \`wrapped\` = payload sits under \`response\`.
*kind*: \`file\` = binary download, \`upload\` = multipart form upload.

`)
for (const dom of DOMAIN_ORDER) {
  const group = ids.filter((id) => domainOf(id) === dom)
  if (!group.length) continue
  doc.push(`## ${dom} (${group.length})\n`)
  doc.push('| Endpoint | Method | Auth | Envelope | Kind | Parameters observed in console |')
  doc.push('| --- | --- | --- | --- | --- | --- |')
  for (const id of group) {
    const meta = paramsByEndpoint.get(id)
    const e = { method: 'GET', auth: NO_AUTH.has(id) ? 'none' : 'token', envelope: FLAT.has(id) ? 'flat' : 'wrapped', kind: FILE_KIND.has(id) ? 'file' : UPLOAD_KIND.has(id) ? 'upload' : 'json' }
    const m = meta?.methods?.join(' \\| ') ?? 'GET'
    const ps = [...new Set([...(meta?.query ?? []), ...(meta?.body ?? [])])].sort().join(', ') || '—'
    doc.push(`| \`${id}\` | ${m} | ${e.auth} | ${e.envelope} | ${e.kind} | ${ps} |`)
  }
  doc.push('')
}
mkdirSync(join(repoRoot, 'docs'), { recursive: true })
writeFileSync(join(repoRoot, 'docs', 'api-endpoints.md'), doc.join('\n') + '\n')

console.log(`registry.ts + docs/api-endpoints.md written for ${ids.length} endpoints`)
const byDomain = {}
for (const id of ids) byDomain[domainOf(id)] = (byDomain[domainOf(id)] ?? 0) + 1
console.log(JSON.stringify(byDomain, null, 0))
